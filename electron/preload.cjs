const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('mobHost', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.send('settings:set', patch),
  onSettings: (fn) => ipcRenderer.on('settings', (_e, s) => fn(s)),
  onCommand: (fn) => ipcRenderer.on('command', (_e, c) => fn(c)),
  setPointerOver: (over) => ipcRenderer.send('pointer:over', over),
  setExpanded: (on) => ipcRenderer.send('window:expand', on),
  reportState: (name) => ipcRenderer.send('state', name),
  setChatFocus: (on) => ipcRenderer.send('chat:focus', on),
  ask: (payload) => ipcRenderer.invoke('assistant:ask', payload),
  onReminder: (fn) => ipcRenderer.on('reminder', (_e, r) => fn(r)),
  rewrite: (mode) => ipcRenderer.send('rewrite:run', mode),
  onRewrite: (fn) => ipcRenderer.on('rewrite', (_e, r) => fn(r)),
  copyText: (text) => ipcRenderer.send('rewrite:copy', text),
  replaceText: (text) => ipcRenderer.invoke('rewrite:replace', text),
  captionsStatus: () => ipcRenderer.invoke('captions:status'),
  askMic: () => ipcRenderer.invoke('captions:askMic'),
  transcribe: (payload) => ipcRenderer.invoke('captions:transcribe', payload),
  openThing: (what) => ipcRenderer.send('open:run', what),
  onTyping: (fn) => ipcRenderer.on('typing', (_e, t) => fn(t)),
  onSay: (fn) => ipcRenderer.on('say', (_e, m) => fn(m)),
  classesList: () => ipcRenderer.invoke('classes:list'),
  saveClass: (cls) => ipcRenderer.invoke('classes:save', cls),
  removeClass: (id) => ipcRenderer.invoke('classes:remove', id),
  joinClass: (id) => ipcRenderer.send('classes:join', id),
  onClassTime: (fn) => ipcRenderer.on('classTime', (_e, m) => fn(m)),
  notesAdd: (line) => ipcRenderer.send('notes:add', line),
  startNotes: () => ipcRenderer.send('notes:start'),
  stopNotes: () => ipcRenderer.send('notes:stop'),
  openNotes: (file) => ipcRenderer.send('notes:open', file),
  onNotes: (fn) => ipcRenderer.on('notes', (_e, n) => fn(n)),
  onNotesDone: (fn) => ipcRenderer.on('notesDone', (_e, n) => fn(n)),
  speak: (text) => ipcRenderer.send('voice:speak', text),
  onSpeaking: (fn) => ipcRenderer.on('speaking', (_e, s) => fn(s)),
  onActivity: (fn) => ipcRenderer.on('activity', (_e, a) => fn(a)),
  onWellbeing: (fn) => ipcRenderer.on('wellbeing', (_e, w) => fn(w)),
});
